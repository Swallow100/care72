export type SeedCell = { value: number | null; shown?: string; frac?: readonly [number, number] };
export type SeedRound = { round: string; values: Record<string, SeedCell> };

const f = (a: number, b: number, shown?: string): SeedCell => ({ value: b > 0 ? a / b : null, frac: [a, b], ...(shown ? { shown } : {}) });
const n = (value: number, shown?: string): SeedCell => ({ value, ...(shown ? { shown } : {}) });
const s = (shown: string): SeedCell => ({ value: null, shown });
const pct = (p: number, shown = `${p}%`): SeedCell => ({ value: p / 100, shown });

