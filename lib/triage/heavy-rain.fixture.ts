import type { Situation, TriageSignal } from "./index.ts";

/** 浸水と停電の時刻（2026-11-05 18:00 JST）。h 時間あとの時刻は at(h) */
export const FLOOD = Date.parse("2026-11-05T09:00:00.000Z");
export const at = (h: number) => new Date(FLOOD + h * 3_600_000).toISOString();

export const LEVEL3 = at(-2);

export function situation(h: number): Situation {
  return { now: at(h), disasterAt: LEVEL3, outageAt: at(0) };
}

