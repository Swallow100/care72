// T88: 仮名化の門の漏れと伏せすぎ（敬称の前の空き・殿・見出しの後ろ・続柄＋名前・かなの名前の文脈・町の字の無い番地・店の語）、
// 入れる欄の戻し（施設名の中の町名・続柄＋名前）。見本の文の名前・住所は全部架空。

import { describe, expect, it } from "vitest";
import { SEED_PEOPLE, seedConsents, type SeedPerson } from "../../seed/people.ts";
import { findLeaks, maskReply, pseudonymize, pseudonymizeText, sourceRestorer, inputTexts, type PseudonymInput } from "./index.ts";

const ON = "2026-11-04";
const input = (p: SeedPerson): PseudonymInput => ({ person: p.person, ledger: p.ledger, contacts: p.contacts, clocks: p.clocks, consents: seedConsents(p) });
const byId = (id: string) => input(SEED_PEOPLE.find((p) => p.person.id === id)!);
const { key } = pseudonymize([byId("p-01")], { on: ON });
const t = (s: string) => pseudonymizeText(s, key).text;

// ---------- 見本の文（架空）。漏れ 0 と、残す言葉 ----------

const SUMMARY = [
  "退院時サマリー",
  "患者氏名：浜野 きくゑ 様（87歳 女性）",
  "住所：中央3-4-5",
  "主治医：杉浦 誠（内科）",
  "入院期間：2026-10-01〜2026-10-20",
  "診断名：誤嚥性肺炎",
  "経過：入院後に抗菌薬で改善。食事は嚥下食。退院日 2026-10-20",
  "退院後：長女 内藤 早苗 様が週3回訪問。本人：浜野 きくゑ",
  "家族の連絡先：090-0000-0031（長女）",
].join("\n");

const LETTER = [
  "診療情報提供書",
  "紹介先：みどり台クリニック 外科 御中",
  "患者氏名：浜野 きくゑ 殿",
  "傷病名：右大腿骨頸部骨折術後",
  "紹介目的：在宅でのリハビリの継続をお願いします。",
  "処方：ワーファリン 1mg 1日1回",
  "キーパーソン：長女 内藤 早苗",
  "氏名:浜野きくゑ",
].join("\n");

const LINE = [
  "長男：母さん、今夜は泊まるよ",
  "母：ありがとう。ひでき、薬は台所にある",
  "長男：わかった。孫のみつきが明日来るって",
  "母：みつき、ありがとうね",
  "18:02\tひでき\tパン屋さんでパン買っていく",
  "ひでき：みつきは学校のあとに寄る",
].join("\n");

/** 見本に埋めた名前・住所（残れば漏れ） */
const SECRETS = ["浜野", "きくゑ", "杉浦 誠", "内藤", "早苗", "中央3-4-5", "ひでき", "みつき", "090-0000-0031"];

describe("見本の文: 漏れ 0（T88）", () => {
  it.each([
    ["退院サマリー", SUMMARY],
    ["紹介状", LETTER],
    ["LINE 風の文", LINE],
  ])("%s", (_, src) => {
    const out = t(src);
    for (const s of SECRETS) expect(out, s).not.toContain(s);
    expect(findLeaks(out, key)).toEqual([]);
  });

  it("残す言葉: 病名・薬・続柄・見出し・施設・日付・店の語", () => {
    const out = t([SUMMARY, LETTER, LINE].join("\n"));
    for (const s of [
      "誤嚥性肺炎",
      "抗菌薬",
      "嚥下食",
      "ワーファリン 1mg 1日1回",
      "右大腿骨頸部骨折術後",
      "長女",
      "長男",
      "母さん",
      "主治医：",
      "（内科）",
      "患者氏名：",
      "キーパーソン：長女",
      "みどり台クリニック 外科 御中",
      "2026-10-01〜2026-10-20",
      "退院日 2026-10-20",
      "パン屋さんでパン買っていく",
      "孫の",
      "ありがとう。",
      "薬は台所にある",
      "学校のあとに寄る",
    ]) {
      expect(out, s).toContain(s);
    }
  });

  it("伏せた形（見出しと続柄は残り、名前と住所だけ印に）", () => {
    expect(t("患者氏名：浜野 きくゑ 様（87歳 女性）")).toBe("患者氏名：（氏名）（87歳 女性）");
    expect(t("住所：中央3-4-5")).toBe("住所：（住所）");
    expect(t("退院後：長女 内藤 早苗 様が週3回訪問")).toBe("退院後：長女 （氏名）が週3回訪問");
    expect(t("母：ありがとう。ひでき、薬は台所にある")).toBe("母：ありがとう。（氏名）、薬は台所にある");
    expect(t("18:02\tひでき\tパン屋さんで")).toBe("18:02\t（氏名）\tパン屋さんで");
  });
});

