// ---------- 入れる欄の戻し（T88） ----------

describe("置き換えの境界と元に戻す印（T88）", () => {
  const p01 = byId("p-01");

  it("続柄＋名前は続柄の役割名 1 つに（「娘の娘」にしない）", () => {
    expect(t("娘の森 恵子さんが来る")).toBe("娘が来る");
    expect(t("娘 森 恵子（090-0000-0011）")).toBe("娘（（電話））");
    expect(t("本人の山田さんは独居")).toBe("A さんは独居");
  });

  it("施設・店の名前の中の姓は仮名・役割名にしない", () => {
    expect(t("山田医院に通う")).toBe("（氏名）医院に通う");
    expect(t("森病院の外来")).not.toContain("娘病院");
  });

  it("台帳の避難先「市坪西小学校」は（町名）小学校で渡り、Claude が写した値は元の言葉に戻る", () => {
    const sources = ["避難先は 市坪西小学校。娘の森 恵子さんが車で送る", ...inputTexts(p01)];
    const back = sourceRestorer(sources, key);
    expect(t(sources[0])).toBe("避難先は （町名）小学校。娘が車で送る");
    expect(back("（町名）小学校")).toBe("市坪西小学校");
    // 役割名は戻さない（続柄の言葉として使われる）
    expect(back("娘")).toBe("娘");
    expect(back("娘が車で送る")).toBe("娘が車で送る");
    // 元の言葉が 1 つに決まらない・どこにも無い値は、仮名だけ氏名に戻し伏せ字は残す（画面が人に直させる）
    expect(back("（町名）公民館")).toBe("（町名）公民館");
    expect(back("A さんは独居")).toBe("山田 ハナさんは独居");
  });

  it("入れた文の伏せ字（台帳に無い名前・住所）も、写した値なら元の言葉に戻る（ケアマネが書いた言葉。Claude には渡っていない）", () => {
    const src = "隣の田中さんが鍵を持っている。娘の家は中央3-4-5";
    const back = sourceRestorer([src], key);
    expect(t(src)).toBe("隣の（氏名）が鍵を持っている。娘の家は（住所）");
    expect(back("（氏名）が鍵を持っている")).toBe("田中さんが鍵を持っている");
    expect(back("（住所）")).toBe("中央3-4-5");
  });
});
